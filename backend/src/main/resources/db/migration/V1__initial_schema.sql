-- Initial schema for the Calme bootstrap.
--
-- Open product decisions are deliberately not encoded here:
--   * authentication strategy and credential columns (docs/QUESTIONS.md #6)
--   * default availability and rest hours (docs/QUESTIONS.md #5)
--   * digest time and email provider (docs/QUESTIONS.md #1 and #7)
--   * capacity ratio (docs/QUESTIONS.md #11)
-- Columns that depend on those decisions are nullable and have no default.

-- Required for the non-overlap constraint on alternance blocks.
create extension if not exists btree_gist;

create table app_user (
    id bigint generated by default as identity primary key,
    email text not null,
    timezone text not null,
    created_at timestamptz not null default now()
);

create unique index app_user_email_lower_unique on app_user (lower(email));

comment on table app_user is
    'Authentication is not implemented yet; credential columns will follow the decision in docs/QUESTIONS.md #6.';

create table block (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id) on delete cascade,
    type text not null,
    start_date date not null,
    end_date date not null,
    default_availability jsonb,
    note text,
    constraint block_type_valid check (type in ('SCHOOL', 'COMPANY')),
    constraint block_dates_valid check (end_date >= start_date)
);

create index block_user_dates_idx on block (user_id, start_date, end_date);

alter table block
    add constraint block_no_overlap
    exclude using gist (
        user_id with =,
        daterange(start_date, end_date, '[]') with &&
    );

comment on column block.default_availability is
    'Null until availability defaults are decided in docs/QUESTIONS.md #5.';

create table project (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id) on delete cascade,
    title text not null,
    goal text not null,
    deadline date not null,
    status text not null,
    buffer_ratio numeric(4, 3) not null,
    created_at timestamptz not null default now(),
    constraint project_buffer_min check (buffer_ratio >= 0.200),
    constraint project_buffer_max check (buffer_ratio <= 1.000)
);

create index project_user_status_deadline_idx on project (user_id, status, deadline);

create table task (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id) on delete cascade,
    project_id bigint references project (id) on delete set null,
    title text not null,
    estimate_min integer not null,
    estimate_max integer not null,
    priority text not null,
    status text not null,
    due_date date,
    created_at timestamptz not null default now(),
    constraint task_estimate_min_positive check (estimate_min > 0),
    constraint task_estimate_range_valid check (estimate_max >= estimate_min),
    constraint task_priority_valid check (priority in ('CRITICAL', 'NORMAL', 'OPTIONAL')),
    constraint task_status_valid check (status in ('TODO', 'DOING', 'DONE', 'DEFERRED'))
);

create index task_user_status_due_idx on task (user_id, status, due_date);
create index task_project_idx on task (project_id);

create table task_dependency (
    task_id bigint not null references task (id) on delete cascade,
    depends_on_task_id bigint not null references task (id) on delete cascade,
    primary key (task_id, depends_on_task_id),
    constraint task_dependency_not_self check (task_id <> depends_on_task_id)
);

create index task_dependency_depends_on_idx on task_dependency (depends_on_task_id);

create table event (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id) on delete cascade,
    task_id bigint references task (id) on delete set null,
    title text not null,
    start_at timestamptz not null,
    end_at timestamptz not null,
    kind text not null,
    recurrence_rule text,
    created_by text not null,
    constraint event_period_valid check (end_at > start_at),
    constraint event_kind_valid check (kind in ('FIXED', 'PLANNED', 'AVAILABILITY')),
    constraint event_created_by_valid check (created_by in ('USER', 'AGENT'))
);

create index event_user_start_idx on event (user_id, start_at);
create index event_task_idx on event (task_id);

create table energy_log (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id) on delete cascade,
    energy_date date not null,
    level text not null,
    source text not null,
    constraint energy_log_level_valid check (level in ('LOW', 'MID', 'GOOD')),
    constraint energy_log_source_valid check (source in ('TAP', 'TEXT'))
);

create index energy_log_user_date_idx on energy_log (user_id, energy_date desc);

create table agent_action (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id) on delete cascade,
    intent text not null,
    payload_json jsonb not null,
    inverse_payload_json jsonb,
    explanation text not null,
    status text not null,
    created_at timestamptz not null default now(),
    constraint agent_action_status_valid check (status in ('APPLIED', 'UNDONE', 'FAILED'))
);

create index agent_action_user_created_idx on agent_action (user_id, created_at desc);

create table message (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id) on delete cascade,
    role text not null,
    content text not null,
    created_at timestamptz not null default now(),
    constraint message_role_valid check (role in ('USER', 'AGENT'))
);

create index message_user_created_idx on message (user_id, created_at desc);

create table settings (
    user_id bigint primary key references app_user (id) on delete cascade,
    rest_start time,
    rest_end time,
    digest_time time,
    capacity_ratio numeric(4, 3),
    tone text,
    constraint settings_capacity_ratio_valid check (capacity_ratio is null or (capacity_ratio > 0 and capacity_ratio <= 1))
);

comment on column settings.rest_start is
    'Null until rest hours are decided; the 22:30 hypothesis is not a validated default.';
comment on column settings.rest_end is
    'Null until rest hours are decided.';
comment on column settings.digest_time is
    'Null until the digest time is decided in docs/QUESTIONS.md #1.';
comment on column settings.capacity_ratio is
    'Null until the 60% capacity hypothesis is calibrated in docs/QUESTIONS.md #11.';

create table digest_log (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id) on delete cascade,
    sent_at timestamptz not null default now(),
    status text not null
);

create index digest_log_user_sent_idx on digest_log (user_id, sent_at desc);
