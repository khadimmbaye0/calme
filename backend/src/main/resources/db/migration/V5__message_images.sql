create table message_image (
    id bigint generated by default as identity primary key,
    message_id bigint not null unique references message (id) on delete cascade,
    media_type text not null,
    byte_size integer not null,
    data bytea not null,
    created_at timestamptz not null default now(),
    constraint message_image_media_type_valid check (media_type in ('image/jpeg', 'image/png', 'image/gif', 'image/webp')),
    constraint message_image_size_positive check (byte_size > 0)
);

create index message_image_message_idx on message_image (message_id);
